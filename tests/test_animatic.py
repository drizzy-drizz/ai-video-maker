def sample_png(path: Path, width=180, height=240, color=(24, 128, 180)):
    """Write a fully decodable RGB PNG without third-party image packages."""
    def chunk(tag, data):
        return (struct.pack(">I", len(data)) + tag + data +
                struct.pack(">I", zlib.crc32(tag + data) & 0xffffffff))
    pixels = b"".join(b"\0" + bytes(color) * width for _ in range(height))
    raw = (b"\x89PNG\r\n\x1a\n" +
           chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)) +
           chunk(b"IDAT", zlib.compress(pixels)) + chunk(b"IEND", b""))
    path.write_bytes(raw)


def sine_wav(path: Path, seconds=1.45, frequency=440):
    with wave.open(str(path), "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(24000)
        frames = int(seconds * 24000)
        audio = b"".join(struct.pack("<h", int(math.sin(t * frequency * 2 * math.pi / 24000) * 4800))
                         for t in range(frames))
        output.writeframes(audio)


class AssetLibraryTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.old_data = app.DATA
        app.DATA = self.root
        self.series = app.new_series({"storyline": "Sofia returned from work and opened the old letter."})

    def tearDown(self):
        app.DATA = self.old_data
        self.tmp.cleanup()

    def test_immutable_asset_versions_and_provenance(self):
        source = self.root / "source.png"
        sample_png(source)
        first = asset_library.add_image_asset(self.root, self.series, str(source),
                                               title="Sofia original", rights="original",
                                               credit="Created by series author")
        self.assertTrue(Path(first["path"]).is_file())
        self.assertNotEqual(Path(first["path"]), source)
        old_bytes = Path(first["path"]).read_bytes()
        sample_png(source, color=(225, 85, 100))
        second = asset_library.add_image_asset(self.root, self.series, str(source),
                                                title="Sofia revised", rights="original",
                                                replace_asset_id=first["id"])
        self.assertEqual(second["version"], 2)
        self.assertEqual(second["parent_asset_id"], first["id"])
        self.assertNotEqual(first["id"], second["id"])
        scene = {"reference_asset_id": first["id"], "script": "Sofia enters."}
        self.assertEqual(asset_library.resolve_image(self.series, scene), Path(first["path"]))
        self.assertEqual(Path(first["path"]).read_bytes(), old_bytes)
        self.assertTrue(asset_library.verify_asset(self.series, first["id"])["valid"])
        self.assertTrue(asset_library.verify_asset(self.series, second["id"])["valid"])
        self.assertNotEqual(first["sha256"], second["sha256"])

    def test_reject_invalid_license_or_missing_asset(self):
        src = self.root / "sample.png"
        sample_png(src)
        with self.assertRaisesRegex(ValueError, "verified image rights"):
            asset_library.add_image_asset(self.root, self.series, str(src), title="Unlicensed", rights="unknown")
        with self.assertRaisesRegex(ValueError, "missing image library asset"):
            asset_library.resolve_image(self.series, {"reference_asset_id": "does-not-exist"})

    def test_binary_http_upload_image_preview_and_saved_project(self):
        project = self.series
        app.save_project(project)
        path = self.root / "browser.png"
        sample_png(path)
        with patch.object(app, "DATA", self.root):
            server = ThreadingHTTPServer(("127.0.0.1", 0), app.AppHandler)
            thread = threading.Thread(target=server.serve_forever, daemon=True)
            thread.start()
            try:
                target = f"http://127.0.0.1:{server.server_port}"
                params = urllib.parse.urlencode({"filename": "browser.png", "title": "Real image",
                                                 "rights": "original", "credit": "Generated by author"})
                request = urllib.request.Request(
                    target + "/api/series/" + project["id"] + "/assets-upload?" + params,
                    data=path.read_bytes(), headers={"Content-Type": "application/octet-stream"})
                with urllib.request.urlopen(request, timeout=10) as response:
                    self.assertEqual(response.status, 201)
                    asset = json.load(response)
                saved = app.read_project(project["id"])
                self.assertEqual(len(saved["assets"]), 1)
                self.assertEqual(saved["assets"][0]["id"], asset["id"])
                with urllib.request.urlopen(
                    target + "/api/assets/" + project["id"] + "/" + asset["id"], timeout=10
                ) as response:
                    self.assertEqual(response.headers.get_content_type(), "image/png")
                    self.assertEqual(response.read(), path.read_bytes())
            finally:
                server.shutdown()
                server.server_close()
                thread.join(timeout=10)


class AnimaticMediaTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.old_data = app.DATA
        app.DATA = self.root
        self.series = app.new_series({"storyline": "Anna meets her sister. They walk home together.",
                                       "format": "9:16"})
        self.episode = self.series["episodes"][0]
        pic = self.root / "approved.png"
        sample_png(pic)
        asset = asset_library.add_image_asset(self.root, self.series, str(pic),
                                               title="Anna approved", rights="original")
        for scene in self.episode["scenes"]:
            scene["reference_asset_id"] = asset["id"]
            scene["duration_hint_seconds"] = 2.2
            scene["animatic_motion"] = "zoom_in"
            scene["clip"] = "C:/original-genuine-footage-unchanged.mp4"

    def tearDown(self):
        app.DATA = self.old_data
        self.tmp.cleanup()

    def test_preflight_refuses_missing_image_and_unlicensed_soundtrack(self):
        scene = self.episode["scenes"][0]
        scene["reference_asset_id"] = "bad-asset-id"
        result = animatic.preflight_animatic(self.series, self.episode)
        self.assertFalse(result["can_render"])
        scene["reference_asset_id"] = self.series["assets"][0]["id"]
        soundtrack = self.root / "music.wav"
        sine_wav(soundtrack, seconds=0.7)
        self.episode["soundtrack"] = str(soundtrack)
        result = animatic.preflight_animatic(self.series, self.episode)
        self.assertFalse(result["can_render"])
        self.episode["soundtrack_rights_confirmed"] = True
        self.assertTrue(animatic.preflight_animatic(self.series, self.episode)["can_render"])

    def test_real_cpu_animatic_render_with_voice_music_and_sidecars(self):
        voice = self.root / "narration.wav"
        song = self.root / "song.wav"
        sine_wav(voice, seconds=2.45)
        sine_wav(song, seconds=0.9, frequency=330)
        scene = self.episode["scenes"][0]
        scene["narration"] = str(voice)
        scene["animatic_motion"] = "pan_right"
        self.episode["soundtrack"] = str(song)
        self.episode["soundtrack_rights_confirmed"] = True
        app.save_project(self.series)
        result = app.render_animatic_episode(self.series["id"], self.episode["id"])
        video = Path(result)
        self.assertTrue(video.is_file())
        info = quality.media_info(video)
        self.assertTrue(info["has_audio"])
        self.assertTrue(info["has_video"])
        self.assertEqual((info["width"], info["height"]), (540, 960))
        self.assertGreaterEqual(info["duration"], 2.7)
        saved = app.read_project(self.series["id"])["episodes"][0]
        self.assertEqual(saved["scenes"][0]["clip"], "C:/original-genuine-footage-unchanged.mp4")
        self.assertEqual(saved["animatic_mode"], "motion_storyboard_NOT_AI_generated_video")
        subtitles = Path(saved["animatic_captions_path"]).read_text(encoding="utf-8-sig")
        self.assertIn("Anna meets", subtitles)
        report = json.loads(Path(saved["animatic_quality_path"]).read_text("utf-8"))
        self.assertTrue(report["music_included"])
        self.assertEqual(report["narration_scene_count"], 1)
        self.assertEqual(report["status"], "technical_checks_passed")
        self.assertIn("NOT AI-generated", report["provenance"])

    def test_camera_motions_generate_distinct_ffmpeg_filters(self):
        generated = {name: animatic._motion_filter(540, 960, 72, name)
                     for name in animatic.MOTIONS}
        self.assertEqual(len(set(generated.values())), len(generated))
        self.assertTrue(all("zoompan" in item and "fps=24" in item for item in generated.values()))


if __name__ == "__main__":
    unittest.main()
